export function buildBreadcrumbNode(items) {
    return {
        '@type': 'BreadcrumbList',
        itemListElement: items.map((item, index) => ({
            '@type': 'ListItem',
            position: index + 1,
            name: item.name,
            item: item.url || (item.path ? `${SITE_URL}${item.path}` : `${SITE_URL}/`),
        })),
    };
}

export function buildFaqNode(faqs) {
    return {
        '@type': 'FAQPage',
        mainEntity: faqs.map((faq) => ({
            '@type': 'Question',
            name: faq.q,
            acceptedAnswer: {
                '@type': 'Answer',
                text: faq.a,
            },
        })),
    };
}

export function buildGraphSchema(nodes) {
    return {
        '@context': 'https://schema.org',
        '@graph': nodes.filter(Boolean),
    };
}

export function buildHomeSchema(faqs = HOME_FAQS) {
    return buildGraphSchema([
        buildOrganizationNode({ includeOfferCatalog: true }),
        {
            '@type': 'WebSite',
            '@id': WEBSITE_ID,
            url: `${SITE_URL}/`,
            name: `${BUSINESS_INFO.name} – Autolackierer Frankfurt`,
            inLanguage: 'de-DE',
            publisher: { '@id': BUSINESS_ID },
        },
        buildFaqNode(faqs),
    ]);
}

export function buildServicePageSchema(service) {
    const pageUrl = `${SITE_URL}/${service.slug}`;
    return buildGraphSchema([
        buildOrganizationNode({ image: `${SITE_URL}${service.heroImage}`, includeOfferCatalog: false }),
        {
            '@type': 'Service',
            '@id': `${pageUrl}#service`,
            name: service.heroTitle,
            serviceType: service.shortTitle,
            description: service.seoDescription,
            url: pageUrl,
            image: `${SITE_URL}${service.heroImage}`,
            provider: { '@id': BUSINESS_ID },
            areaServed: ALL_AREAS_SERVED,
        },
        buildBreadcrumbNode([
            { name: 'Startseite', url: `${SITE_URL}/` },
            { name: service.shortTitle, url: pageUrl },
        ]),
        service.faqs && service.faqs.length > 0 ? buildFaqNode(service.faqs) : null,
    ]);
}

export function buildRegionalPageSchema(page) {
    const pageUrl = `${SITE_URL}/${page.slug}`;
    return buildGraphSchema([
        buildOrganizationNode({
            url: pageUrl,
            image: `${SITE_URL}${page.image}`,
            description: page.description,
            areaServed: page.areaServed,
            includeOfferCatalog: true,
        }),
        {
            '@type': 'Service',
            '@id': `${pageUrl}#regional-service`,
            name: page.heroHeading,
            serviceType: 'Autolackierung & Dellentechnik',
            description: page.description,
            url: pageUrl,
            image: `${SITE_URL}${page.image}`,
            provider: { '@id': BUSINESS_ID },
            areaServed: {
                '@type': page.areaType || 'City',
                name: page.areaServed,
            },
        },
        buildBreadcrumbNode([
            { name: 'Startseite', url: `${SITE_URL}/` },
            { name: page.breadcrumbLabel || page.city, url: pageUrl },
        ]),
        page.faqs && page.faqs.length > 0 ? buildFaqNode(page.faqs) : null,
    ]);
}

export function buildGalleryPageSchema(images = []) {
    const pageUrl = `${SITE_URL}/galerie`;
    return buildGraphSchema([
        buildOrganizationNode({ includeOfferCatalog: false }),
        {
            '@type': 'ImageGallery',
            '@id': `${pageUrl}#gallery`,
            name: GALERIE_SEO.title,
            description: GALERIE_SEO.description,
            url: pageUrl,
            about: { '@id': BUSINESS_ID },
            ...(images.length > 0
                ? {
                    image: images.map((item) => ({
                        '@type': 'ImageObject',
                        contentUrl: `${SITE_URL}${item.src}`,
                        name: item.title,
                        description: item.alt,
                    })),
                }
                : {}),
        },
        buildBreadcrumbNode([
            { name: 'Startseite', url: `${SITE_URL}/` },
            { name: 'Galerie & Referenzen', url: pageUrl },
        ]),
    ]);
}

export const buildGallerySchema = buildGalleryPageSchema;
